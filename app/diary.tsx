  input: { borderWidth: 1, borderRadius: 0, padding: 12, fontSize: 15, marginBottom: 8 },
  textArea: { minHeight: 70, textAlignVertical: "top" },
  timeRow: { flexDirection: "row", alignItems: "center", gap: 6 },
