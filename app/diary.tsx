  header: { flexDirection: "row", alignItems: "center", marginBottom: 16 },
  backBtn: { padding: 8, marginRight: 8 },
  title: { fontSize: 22, fontWeight: "700", flex: 1 },
  addBtn: { padding: 8 },
  summaryCard: { flexDirection: "row", alignItems: "center", gap: 12, padding: 14, borderRadius: 0, borderWidth: 1, marginBottom: 16 },
  summaryText: { flex: 1 },
  summaryTitle: { fontSize: 16, fontWeight: "600" },
  summarySubtitle: { fontSize: 13, marginTop: 2 },
  list: { paddingBottom: 20 },
  entryCard: { padding: 14, borderRadius: 0, borderWidth: 1, marginBottom: 8 },
  entryHeader: { flexDirection: "row", alignItems: "center", justifyContent: "space-between" },
  dateContainer: { flexDirection: "row", alignItems: "center", gap: 6 },
  entryDate: { fontSize: 15, fontWeight: "600" },
  autoBadge: { paddingHorizontal: 8, paddingVertical: 3, borderRadius: 0 },
  autoBadgeText: { fontSize: 11, fontWeight: "600" },
  weatherText: { fontSize: 13, marginTop: 4 },
  entryStats: { flexDirection: "row", gap: 12, marginTop: 8 },
  entryStat: { flexDirection: "row", alignItems: "center", gap: 4 },
  entryStatText: { fontSize: 12 },
  activityPreview: { fontSize: 13, marginTop: 8 },
  emptyState: { alignItems: "center", paddingTop: 60, gap: 12 },
  emptyText: { fontSize: 16, fontWeight: "500" },
  emptySubtext: { fontSize: 13, textAlign: "center", paddingHorizontal: 32 },
  modalOverlay: { flex: 1, backgroundColor: "rgba(0,0,0,0.5)", justifyContent: "flex-end" },
  modalContent: { borderTopLeftRadius: 20, borderTopRightRadius: 20, padding: 24, maxHeight: "90%" },
  modalTitle: { fontSize: 18, fontWeight: "700" },
  modalSubtitle: { fontSize: 14, marginTop: 4, marginBottom: 16 },
  detailSection: { fontSize: 14, marginTop: 8 },
  detailBlock: { marginTop: 16 },
  detailLabel: { fontSize: 15, fontWeight: "600", marginBottom: 6 },
  detailItem: { fontSize: 14, marginBottom: 3 },
  closeBtn: { paddingVertical: 14, borderRadius: 0, alignItems: "center", marginTop: 16 },
  closeBtnText: { color: "#fff", fontSize: 15, fontWeight: "600" },
